import { render, screen } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import { BriefingModal } from "@/components/property/BriefingModal";
import type { BriefingSource } from "@/lib/api";

const renderModal = (source: BriefingSource) =>
  render(
    <BriefingModal
      items={[{ type: "bullet", text: "Heating failed twice", hasGap: false }]}
      latencyMs={1200}
      source={source}
      onClose={vi.fn()}
      onRegenerate={vi.fn(async () => {})}
    />,
  );

describe("BriefingModal", () => {
  it("does not present a keyless briefing as model-written", () => {
    renderModal("unavailable");

    expect(
      screen.getByText(/Built from the property file; no language model configured/),
    ).toBeInTheDocument();
    expect(screen.queryByText(/Generated by the language model/)).not.toBeInTheDocument();
  });

  it("names the model and the cache when they produced it", () => {
    const { unmount } = renderModal("llm");
    expect(screen.getByText(/Generated by the language model/)).toBeInTheDocument();
    unmount();

    renderModal("cache");
    expect(screen.getByText(/Cached from an earlier model run/)).toBeInTheDocument();
  });
});
