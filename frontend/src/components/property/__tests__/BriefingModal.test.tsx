import { render, screen } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import { BriefingModal } from "@/components/property/BriefingModal";
import type { BriefingSource } from "@/lib/api";

const renderModal = (source: BriefingSource) =>
  render(
    <BriefingModal
      items={[{ type: "bullet", text: "Heating failed twice", hasGap: false }]}
      latencyMs={1200}
      source={source}
      onClose={vi.fn()}
      onRegenerate={vi.fn(async () => {})}
    />,
  );

describe("BriefingModal", () => {
  it("does not present a keyless briefing as LLM-written", () => {
    renderModal("unavailable");

    expect(screen.getByText(/Built from the property file, no LLM key/)).toBeInTheDocument();
    expect(screen.queryByText(/Generated by the LLM provider/)).not.toBeInTheDocument();
  });

  it("names the LLM and the cache when they produced it", () => {
    const { unmount } = renderModal("llm");
    expect(screen.getByText(/Generated by the LLM provider/)).toBeInTheDocument();
    unmount();

    renderModal("cache");
    expect(screen.getByText(/Cached LLM briefing/)).toBeInTheDocument();
  });
});
